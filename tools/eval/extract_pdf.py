#!/usr/bin/env python3
"""Ground truth from the specimen PDF. Read-only on the datasets directory.

The PDF is generated by ReportLab: printed labels use Helvetica, the simulated
handwriting uses another font per patient (Caveat, Shadows Into Light, ...), checkboxes are vector squares, ticks are blue
vector strokes and table grids are vector lines. So the printed template and
the written values can be separated exactly, without OCR.

Writes (under tools/eval/data):
  ground_truth.json  {page_no: {patient, page_type, layout, slots: [...]}}
  masks.json         {layout: [bbox_frac]} areas of the identifier fields (no label, no value)

Direct identifiers (woman's name, CIN, address, phone, husband's name and job)
never reach the outputs; staff names are replaced by "<staff>".

Usage: extract_pdf.py [--pdf FILE] [--out DIR] [--pages 2,3,4]
"""
import argparse
import json
import math
import os
import re
import sys
import unicodedata
from pathlib import Path

import fitz

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
PDF_NAME = "dossiers_specimen_10_patientes.pdf"
PAGES_PER_PATIENT = 8
LAYOUT = {1: "cover", 2: "identification", 3: "pregnancy", 4: "delivery",
          5: "postpartum_mother", 6: "postpartum_newborn", 7: "postpartum_mother", 8: "postpartum_newborn"}

STAFF = "<staff>"
# Slug of the printed label of each direct identifier field.
IDENTIFIER_LABELS = {"nom_prenom_de_la_parturiente", "cin", "adresse", "telephone", "nom_du_mari", "patiente"}
STAFF_LABELS = {"examen_fait_par", "vu_par"}
BODY_Y = (58, 812)  # outside: page title, specimen stamp, "MÈRE — <name>" header, footer


def slug(text):
    t = text.replace("œ", "oe").replace("Œ", "OE").replace("°", " deg").replace("+", " plus ")
    t = re.sub(r"-\s*$", " minus", t.strip())
    t = unicodedata.normalize("NFD", t)
    t = "".join(c for c in t if not unicodedata.combining(c)).lower()
    return re.sub(r"[^a-z0-9]+", "_", t).strip("_")


def abbrev(s):
    """Short column ids: visite_2 -> v2, 1er_trimestre -> t1, 7eme_mois -> m7."""
    for pat, rep in ((r"^visite_(\d+)$", r"v\1"), (r"^(\d+)(?:er|e|eme)_trimestre$", r"t\1"), (r"^(\d+)eme_mois$", r"m\1")):
        s = re.sub(pat, rep, s)
    return s


class Box:
    def __init__(self, x0, y0, x1, y1):
        self.x0, self.y0, self.x1, self.y1 = x0, y0, x1, y1

    @property
    def xc(self):
        return (self.x0 + self.x1) / 2

    @property
    def yc(self):
        return (self.y0 + self.y1) / 2

    def contains(self, x, y, pad=0):
        return self.x0 - pad <= x <= self.x1 + pad and self.y0 - pad <= y <= self.y1 + pad

    def union(self, o):
        return Box(min(self.x0, o.x0), min(self.y0, o.y0), max(self.x1, o.x1), max(self.y1, o.y1))

    def pad(self, p):
        return Box(self.x0 - p, self.y0 - p, self.x1 + p, self.y1 + p)

    def tuple(self):
        return (self.x0, self.y0, self.x1, self.y1)


class Span(Box):
    def __init__(self, text, bbox, bold, chars):
        super().__init__(*bbox)
        self.text, self.bold, self.chars = text.strip(), bold, chars


def read_page(page):
    """Printed spans, handwritten chars and vector shapes of one page (points)."""
    printed, hand = [], []
    for b in page.get_text("rawdict")["blocks"]:
        for l in b.get("lines", []):
            for s in l["spans"]:
                if not s["font"].startswith("Helvetica"):  # every patient has its own handwriting font
                    for c in s["chars"]:
                        # The font's own bbox is unreliable (ascent/descent differ per font): keep x, rebuild y from the baseline.
                        x0, _, x1, _ = c["bbox"]
                        base = c["origin"][1]
                        hand.append((c["c"], Box(x0, base - 0.7 * s["size"], x1, base + 0.1 * s["size"]), c["origin"][0], s["size"]))
                elif "".join(c["c"] for c in s["chars"]).strip():
                    text = "".join(c["c"] for c in s["chars"])
                    printed.append(Span(text, s["bbox"], "Bold" in s["font"], [(c["c"], Box(*c["bbox"])) for c in s["chars"]]))
    shapes = dict(boxes=[], squares=[], ticks=[], hlines=[], vlines=[], fills=[])
    for d in page.get_drawings():
        r, items, col = d["rect"], d["items"], d["color"]
        if d["fill"] is not None and col is None:
            if r.width < page.rect.width - 1:
                shapes["fills"].append(Box(r.x0, r.y0, r.x1, r.y1))
        elif len(items) == 4 and all(i[0] == "l" for i in items):
            b = Box(r.x0, r.y0, r.x1, r.y1)
            if 6 <= r.width <= 13 and abs(r.width - r.height) < 2.5:
                shapes["squares"].append(b)
            else:
                shapes["boxes"].append(b)
        elif all(i[0] == "l" for i in items) and len(items) <= 2:
            b = Box(r.x0, r.y0, r.x1, r.y1)
            # Pages are slightly skewed (up to ~0.5 deg), so rules are not exactly axis-aligned.
            if r.height <= 2 + 0.02 * r.width and r.width >= 15:
                shapes["hlines"].append(b)
            elif r.width <= 2 + 0.02 * r.height and r.height >= 15:
                shapes["vlines"].append(b)
            elif 4 <= r.width <= 22 and 4 <= r.height <= 22:
                shapes["ticks"].append(b)  # ink colour differs per patient: recognised by shape
    return printed, hand, shapes


def cluster(values, tol):
    out = []
    for v in sorted(values):
        if out and v - out[-1][-1] <= tol:
            out[-1].append(v)
        else:
            out.append([v])
    return [sum(g) / len(g) for g in out]


def hand_text(chars):
    """Chars of one slot -> text: lines top to bottom, left to right, as in the text layer."""
    lines = []
    for ch in sorted(chars, key=lambda c: c[1].yc):
        if lines and abs(lines[-1][0] - ch[1].yc) < 0.6 * ch[3]:
            lines[-1][1].append(ch)
        else:
            lines.append([ch[1].yc, [ch]])
    text = " ".join("".join(c[0] for c in sorted(l[1], key=lambda c: c[2])) for l in lines)
    return re.sub(r"\s+", " ", text).strip()


def find_tables(shapes, printed):
    """Boxes with inner full-width rules and column rules -> grids (rows x cols)."""
    tables = []
    for bx in shapes["boxes"]:
        if bx.x1 - bx.x0 < 100 or bx.y1 - bx.y0 < 40:
            continue
        hl = [l for l in shapes["hlines"] if bx.contains(l.xc, l.yc, 2) and l.x1 - l.x0 >= 0.85 * (bx.x1 - bx.x0)]
        vl = [l for l in shapes["vlines"] if bx.contains(l.xc, l.yc, 2) and l.y1 - l.y0 >= 0.4 * (bx.y1 - bx.y0)]
        if not hl or not vl:
            continue
        ys = [bx.y0] + [y for y in cluster([l.yc for l in hl], 2) if bx.y0 + 3 < y < bx.y1 - 3] + [bx.y1]
        xs = [bx.x0] + [x for x in cluster([l.xc for l in vl], 3) if bx.x0 + 3 < x < bx.x1 - 3] + [bx.x1]
        tables.append(dict(box=bx, ys=ys, xs=xs, vlines=vl))
    return sorted(tables, key=lambda t: t["box"].y0)


def spans_in(printed, r):
    return sorted((s for s in printed if r.contains(s.xc, s.yc)), key=lambda s: (round(s.yc / 4), s.x0))


def table_slots(t, printed, shapes, page_no, heading):
    """Cells of one table. Returns slot dicts (value filled later) and the rows' metadata."""
    xs, ys, vls = t["xs"], t["ys"], t["vlines"]
    nr, nc = len(ys) - 1, len(xs) - 1
    cell = lambda i, j: Box(xs[j], ys[i], xs[j + 1], ys[i + 1])
    row_box = lambda i: Box(xs[0], ys[i], xs[-1], ys[i + 1])
    bands = [i for i in range(nr) if any(f.contains(row_box(i).xc, row_box(i).yc) for f in shapes["fills"])]
    has_label_col = any(spans_in(printed, cell(i, 0)) for i in range(1, nr) if i not in bands)
    first_val = 1 if has_label_col else 0
    header = []
    for i in range(nr):
        if i in bands or not any(spans_in(printed, cell(i, j)) for j in range(first_val, nc)):
            break
        header.append(i)

    def header_cell(i, j):
        """Merged header cell of column j in header row i: bounded by the column rules that cross that row."""
        cross = sorted(v.xc for v in vls if v.y0 <= row_box(i).yc <= v.y1) + [xs[0], xs[-1]]
        cross = sorted(set(cross))
        left = max(x for x in cross if x <= cell(i, j).xc)
        right = min(x for x in cross if x > cell(i, j).xc)
        return Box(left, ys[i], right, ys[i + 1])

    cols = []
    for j in range(first_val, nc):
        parts = []
        for i in reversed(header):
            txt = " ".join(s.text for s in spans_in(printed, header_cell(i, j)) if s.x0 >= xs[first_val] - 1)
            if txt:
                parts.append(abbrev(slug(txt)))
        cols.append("_".join(parts) or f"c{j}")

    slots, section = [], None
    for i in range(nr):
        if i in header:
            continue
        label_spans = spans_in(printed, cell(i, 0)) if has_label_col else []
        label = " ".join(s.text for s in label_spans)
        if i in bands:
            section = label
            continue
        row_label = label or heading
        for j in range(first_val, nc):
            slots.append(dict(label=row_label, section=section, column=cols[j - first_val], kind="text",
                              box=cell(i, j), base=f"p{page_no:02d}.{slug(row_label)}.{cols[j - first_val]}", origin="table"))
    return slots


def nearest_left(printed, ref, y, max_gap=1e9, exclude=()):
    """Printed span ending left of x=ref on the same line as y, nearest first."""
    best = None
    for s in printed:
        if s in exclude or abs(s.yc - y) > 8 or s.x1 > ref + 3:
            continue
        gap = ref - s.x1
        if gap <= max_gap and (best is None or gap < best[0]):
            best = (gap, s)
    return best[1] if best else None


def extract_page(page, page_no, issues):
    pt = ((page_no - 1) % PAGES_PER_PATIENT) + 1
    pt = {7: 5, 8: 6}.get(pt, pt)  # pages 7 and 8 reuse the layouts, hence the keys, of pages 5 and 6
    printed, hand, shapes = read_page(page)
    W, H = page.rect.width, page.rect.height
    body = [s for s in printed if BODY_Y[0] < s.yc < BODY_Y[1]]
    tables = find_tables(shapes, printed)
    in_table = lambda s: any(t["box"].contains(s.xc, s.yc) for t in tables)
    free = [s for s in body if not in_table(s)]
    bolds = sorted((s for s in free if s.bold), key=lambda s: s.yc)

    def section_of(y):
        prev = [s for s in bolds if s.yc <= y + 8]
        return prev[-1].text.rstrip(" :") if prev else None

    slots = []
    for t in tables:
        b = t["box"]
        above = [s for s in bolds if s.yc < b.y0 + 2 and s.x0 < b.x1 and s.x1 > b.x0]
        heading = above[-1].text if above else ""
        ts = table_slots(t, printed, shapes, pt, heading)
        for s in ts:
            s["section"] = s["section"] or heading or None
        slots += ts

    # Checkboxes: square + label right of it (else left), tick = a blue stroke centred in the square.
    unused_ticks = list(shapes["ticks"])
    for sq in sorted(shapes["squares"], key=lambda b: (round(b.yc / 4), b.x0)):
        if any(t["box"].contains(sq.xc, sq.yc) for t in tables):
            continue
        mine = [k for k in unused_ticks if sq.contains(k.xc, k.yc, 3)]
        for k in mine:
            unused_ticks.remove(k)
        right = [s for s in free if -1 <= s.x0 - sq.x1 <= 16 and abs(s.yc - sq.yc) <= 6]
        lab = min(right, key=lambda s: s.x0 - sq.x1) if right else nearest_left(free, sq.x0, sq.yc, 100)
        if lab is None:
            issues.append(f"page {page_no}: checkbox at ({sq.x0:.0f},{sq.y0:.0f}) has no label")
        text = lab.text.rstrip(" :") if lab else f"checkbox_{round(sq.yc)}_{round(sq.x0)}"
        # Context for ambiguous labels: ':' segment on the same line to the left, else the nearest above.
        colon = [s for s in free if s.text.rstrip().endswith(":") and s is not lab]
        same = [s for s in colon if abs(s.yc - sq.yc) <= 6 and s.x1 <= sq.x0]
        above = [s for s in colon if 4 < sq.yc - s.yc <= 90 and s.x0 <= sq.x0 + 2]
        group = max(same, key=lambda s: s.x1) if same else (max(above, key=lambda s: s.yc) if above else None)
        slots.append(dict(label=text, section=section_of(sq.yc), kind="checkbox", value=bool(mine), box=sq,
                          base=f"p{pt:02d}.{slug(text)}", group=slug(group.text) if group else "",
                          short=len(slug(text)) <= 2, group_same_line=bool(same), origin="checkbox"))
    for k in unused_ticks:
        issues.append(f"page {page_no}: tick at ({k.x0:.0f},{k.y0:.0f}) is not inside a checkbox")

    # Underlined fields: the label is the printed text left of the rule.
    for l in sorted(shapes["hlines"], key=lambda b: (round(b.yc / 4), b.x0)):
        if any(t["box"].pad(2).contains(l.xc, l.yc) for t in tables) or not 20 <= l.x1 - l.x0 <= 500:
            continue
        lab = nearest_left(free, l.x0, l.yc - 4)
        if lab is None:
            issues.append(f"page {page_no}: underline at ({l.x0:.0f},{l.yc:.0f}) has no label")
        text = lab.text.rstrip(" :") if lab else f"field_{round(l.yc)}_{round(l.x0)}"
        ctx = nearest_left(free, lab.x0 - 2, l.yc - 4) if lab else None
        slots.append(dict(label=text, section=section_of(l.yc), kind="text", box=Box(l.x0 - 2, l.yc - 14, l.x1 + 2, l.yc + 3),
                          base=f"p{pt:02d}.{slug(text)}", group=slug(ctx.text) if ctx else "", origin="underline",
                          label_box=lab))

    # Dotted fields ("Autres à préciser : ........").
    for s in free:
        m = re.search(r"\.{5,}", "".join(c for c, _ in s.chars))
        if not m:
            continue
        text = s.text[:m.start()].rstrip(" :") or "autres"
        dots = [b for c, b in s.chars[m.start():m.end()]]
        slots.append(dict(label=text, section=section_of(s.yc), kind="text",
                          box=Box(dots[0].x0, s.y0 - 6, dots[-1].x1, s.y1 + 3), base=f"p{pt:02d}.{slug(text)}",
                          group="", origin="dotted", label_box=s))

    # Identifier / staff fields: decided on the printed label (and the husband's "Profession", same line as "Nom du Mari").
    excluded, kept = [], []
    for s in slots:
        sl = slug(s["label"])
        husband = sl == "profession" and any(slug(p.text.rstrip(" :")) == "nom_du_mari" and abs(p.yc - s["box"].yc) < 12 for p in free)
        if s["origin"] in ("underline", "dotted") and (sl in IDENTIFIER_LABELS or husband):
            excluded.append(s)
        else:
            kept.append(s)
    slots = kept

    # Assign handwriting: tables, then fields; the rest is attached to the nearest label.
    pool = list(hand)

    def take(box):
        got = [c for c in pool if box.contains(c[1].xc, c[1].yc)]
        for c in got:
            pool.remove(c)
        return got

    for s in excluded:
        s["chars"] = take(s["box"])
    for s in slots:
        if s["origin"] in ("table", "underline", "dotted"):
            s["chars"] = take(s["box"])
    # Handwriting outside every template slot: lines of the pool, split at wide gaps, one slot per nearest label.
    lines = []
    for c in sorted(pool, key=lambda c: c[1].yc):
        if lines and abs(sum(x[1].yc for x in lines[-1]) / len(lines[-1]) - c[1].yc) < 0.6 * c[3]:
            lines[-1].append(c)
        else:
            lines.append([c])
    runs = []
    for line in lines:
        line.sort(key=lambda c: c[2])
        runs.append([line[0]])
        for c in line[1:]:
            if c[1].x0 - runs[-1][-1][1].x1 > 25:
                runs.append([c])
            else:
                runs[-1].append(c)
    merged = {}
    for run in runs:
        box = run[0][1]
        for c in run:
            box = box.union(c[1])
        lab = nearest_left(free, box.x0, box.yc, 200)
        if lab is None:
            above = [s for s in free if 0 < box.y0 - s.y1 <= 30 and s.x0 <= box.x1]
            lab = max(above, key=lambda s: s.yc) if above else None
        if lab is None:
            issues.append(f"page {page_no}: handwriting '{hand_text(run)}' at ({box.x0:.0f},{box.y0:.0f}) has no label")
        text = lab.text.rstrip(" :") if lab else f"text_{round(box.yc)}"
        if text in merged:
            merged[text]["chars"] += run
            merged[text]["box"] = merged[text]["box"].union(box.pad(2))
        else:
            merged[text] = dict(label=text, section=section_of(box.yc), kind="text", box=box.pad(2),
                                base=f"p{pt:02d}.{slug(text)}_text", group="", origin="orphan", chars=list(run))
    for entry in merged.values():
        (excluded if slug(entry["label"]) in IDENTIFIER_LABELS else slots).append(entry)

    forbidden = [hand_text(s["chars"]) for s in excluded if s.get("chars")]
    out = []
    for s in slots:
        if s["kind"] == "text":
            v = hand_text(s.get("chars", []))
            if v and slug(s["label"]) in STAFF_LABELS:
                v = STAFF
            s["value"] = v
        out.append(s)
    masks = []
    for s in excluded:
        b = s["box"]
        if s.get("label_box"):
            b = b.union(s["label_box"])
        for c in s.get("chars", []):
            b = b.union(c[1])
        masks.append(b.pad(2))
    return out, masks, forbidden, (printed, shapes)


def finalize_keys(slots):
    """Stable unique keys. Ambiguous or very short labels get their context; leftovers get _2, _3."""
    count = {}
    for s in slots:
        count[s["base"]] = count.get(s["base"], 0) + 1
    used = {}
    for s in slots:
        key = s["base"]
        ctx = s.get("group", "")
        if ctx and (count[key] > 1 or (s.get("short") and s.get("group_same_line"))):
            head, _, tail = key.partition(".")
            key = f"{head}.{ctx}_{tail}" if s.get("short") else f"{head}.{tail}_{ctx}"
        used[key] = used.get(key, 0) + 1
        s["key"] = key if used[key] == 1 else f"{key}_{used[key]}"


def frac(b, W, H):
    return [round(b.x0 / W, 4), round(b.y0 / H, 4), round(b.x1 / W, 4), round(b.y1 / H, 4)]


def sort_slots(slots):
    return sorted(slots, key=lambda s: (round(s["box"].yc / 4), s["box"].x0))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--pdf")
    ap.add_argument("--out", default=str(HERE / "data"))
    ap.add_argument("--pages", help="comma list of page numbers (default: all)")
    a = ap.parse_args()
    datasets = Path(os.environ.get("DATASETS_DIR") or REPO.parent / "datasets").resolve()
    pdf = Path(a.pdf) if a.pdf else datasets / "data" / "Paper Registry" / PDF_NAME
    out_dir = Path(a.out).resolve()
    if datasets == out_dir or datasets in out_dir.parents:
        sys.exit("refusing to write inside the datasets directory")
    doc = fitz.open(pdf)
    W, H = doc[0].rect.width, doc[0].rect.height
    wanted = {int(n) for n in a.pages.split(",")} if a.pages else set(range(1, doc.page_count + 1))

    issues, pages, all_masks, forbidden, geo = [], {}, {}, [], {}
    for no in sorted(wanted):
        slots, masks, forb, geom = extract_page(doc[no - 1], no, issues)
        forbidden += forb
        pt = ((no - 1) % PAGES_PER_PATIENT) + 1
        layout = LAYOUT[pt]
        slots = sort_slots(slots)
        finalize_keys(slots)
        pages[no] = dict(patient=math.ceil(no / PAGES_PER_PATIENT), page_type=pt, layout=layout, slots=slots)
        all_masks.setdefault(layout, []).extend(masks)
        geo[no] = geom
        for s in slots:
            if s["origin"] == "orphan":
                issues.append(f"info page {no}: handwriting outside any template slot attached to '{s['label']}' ({s['key']})")

    # Layout key universe: orphan slots exist for every page of the layout (empty where nobody wrote);
    # template slots do not, pages 5 and 7 share a layout but not every printed option.
    by_layout = {}
    for no, p in pages.items():
        by_layout.setdefault(p["layout"], {})
        for s in p["slots"]:
            u = by_layout[p["layout"]].setdefault(s["key"], dict(s, box=s["box"], order=len(by_layout[p["layout"]])))
            u["box"] = u["box"].union(s["box"]) if s["origin"] == "orphan" else u["box"]
    for no, p in pages.items():
        have = {s["key"] for s in p["slots"]}
        for key, u in by_layout[p["layout"]].items():
            if key not in have and u["origin"] == "orphan":
                p["slots"].append(dict(u, value="" if u["kind"] == "text" else False))
        p["slots"] = sorted(p["slots"], key=lambda s: by_layout[p["layout"]][s["key"]]["order"])
        # orphan boxes: use the union over the layout
        for s in p["slots"]:
            if s["origin"] == "orphan":
                s["box"] = by_layout[p["layout"]][s["key"]]["box"]

    gt = {}
    for no, p in pages.items():
        gt[str(no)] = dict(patient=p["patient"], page_type=p["page_type"], layout=p["layout"], slots=[
            {k: v for k, v in dict(key=s["key"], label=s["label"], section=s["section"], column=s.get("column"), kind=s["kind"],
                                  value=s["value"], bbox_frac=frac(s["box"], W, H)).items() if v is not None}
            for s in p["slots"]])
    masks_out = {}
    for layout, ms in all_masks.items():
        u = []
        for m in ms:  # merge identical areas across patients
            for i, o in enumerate(u):
                if abs(o.x0 - m.x0) < 15 and abs(o.y0 - m.y0) < 15:
                    u[i] = o.union(m)
                    break
            else:
                u.append(m)
        masks_out[layout] = [frac(m, W, H) for m in u]

    # The excluded values must not appear anywhere in what we write.
    text = json.dumps(gt, ensure_ascii=False) + json.dumps(masks_out)
    squash = lambda s: re.sub(r"[\s.,/-]+", "", unicodedata.normalize("NFD", s).lower())
    hay = squash(text)
    for f in forbidden:
        if len(squash(f)) >= 5 and squash(f) in hay:
            sys.exit("an excluded identifier value leaked into the outputs; aborting without writing")

    out_dir.mkdir(parents=True, exist_ok=True)
    write_gt(out_dir / "ground_truth.json", gt)
    (out_dir / "masks.json").write_text(json.dumps(masks_out, indent=1) + "\n")
    report(gt, pages, geo, issues, all_masks)


def write_gt(path, gt):
    lines = ["{"]
    for i, (no, p) in enumerate(gt.items()):
        head = json.dumps({k: v for k, v in p.items() if k != "slots"}, ensure_ascii=False)[:-1]
        lines.append(f'"{no}": {head}, "slots": [')
        lines.append(",\n".join(" " + json.dumps(s, ensure_ascii=False, separators=(",", ":")) for s in p["slots"]))
        lines.append("]}" + ("," if i < len(gt) - 1 else ""))
    lines.append("}")
    path.write_text("\n".join(lines) + "\n")


def report(gt, pages, geo, issues, masks):
    print("layout            pages  slots  text  checkbox  non-empty  ticked  excluded-id-slots")
    for layout in dict.fromkeys(p["layout"] for p in gt.values()):
        ps = [p for p in gt.values() if p["layout"] == layout]
        sl = [s for p in ps for s in p["slots"]]
        txt = [s for s in sl if s["kind"] == "text"]
        print(f"{layout:<17} {len(ps):>5} {len(sl):>6} {len(txt):>5} {len(sl) - len(txt):>9} "
              f"{sum(1 for s in txt if s['value']):>10} {sum(1 for s in sl if s['kind'] == 'checkbox' and s['value']):>7} "
              f"{len(masks.get(layout, [])):>8} (areas, merged over patients)")
    # Cross-patient geometry: slots by key, and printed text / rules by position in reading order.
    print("cross-patient geometry (points; page is 595 x 842):")
    for pt in sorted({p["page_type"] for p in gt.values()}):
        nos = [n for n, p in pages.items() if p["page_type"] == pt]
        layout = LAYOUT[pt]
        ref = {s["key"]: s["box"] for s in pages[nos[0]]["slots"] if s["origin"] != "orphan"}
        dslot = 0.0
        for n in nos[1:]:
            for s in pages[n]["slots"]:
                if s["key"] in ref and s["origin"] != "orphan":
                    dslot = max(dslot, max(abs(a - b) for a, b in zip(s["box"].tuple(), ref[s["key"]].tuple())))
        dtext, mism, dgrid, gridmis = 0.0, 0, 0.0, 0
        stamp = lambda sp: sp.text.startswith(("MÈRE", "Patiente fictive"))
        dist = lambda x, y: max(abs(p - q) for p, q in zip(x.tuple(), y.tuple()))
        for n in nos[1:]:
            g, gref = geo[int(n)], geo[int(nos[0])]
            for x in (sp for sp in gref[0] if not stamp(sp)):
                cands = [dist(x, y) for y in g[0] if y.text == x.text]
                if cands:
                    dtext = max(dtext, min(cands))
                else:
                    mism += 1
            for kind in ("hlines", "vlines", "squares", "boxes"):
                if len(gref[1][kind]) != len(g[1][kind]):
                    gridmis += 1
                for x in gref[1][kind]:
                    cands = [dist(x, y) for y in g[1][kind]]
                    dgrid = max(dgrid, min(cands)) if cands else dgrid
        print(f"  p{pt} {layout:<17} slot boxes {dslot:.2f}  printed text {dtext:.2f} (text/count mismatches {mism})  rules/boxes {dgrid:.2f} (count mismatches {gridmis})")
    infos = [i for i in issues if i.startswith("info")]
    probs = [i for i in issues if not i.startswith("info")]
    print(f"could not attach: {len(probs)}")
    for i in probs:
        print("  " + i)
    kinds = {}
    for i in infos:
        kinds.setdefault(re.search(r"\((p\d\d\.[^)]*)\)$", i).group(1), []).append(re.search(r"page (\d+)", i).group(1))
    print(f"handwriting outside every printed slot, attached to the nearest label ({len(infos)} cases):")
    for key, nos in sorted(kinds.items()):
        print(f"  {key}: pages {', '.join(nos)}")


