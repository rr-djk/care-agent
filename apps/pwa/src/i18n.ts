const TABLES: Record<Lang, Record<Key, string>> = { fr, en };
const STORAGE_KEY = 'care-agent.lang';

function load(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === 'fr' || v === 'en') return v;
  } catch {
    // storage blocked (private window, preview): French
  }
  return 'fr';
}

let lang: Lang = load();
const listeners = new Set<() => void>();

export const getLang = () => lang;

export function setLang(next: Lang) {
  if (next === lang) return;
  lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // not remembered: the choice still holds until the page is reloaded
  }
  for (const l of listeners) l();
}

export function subscribeLang(listener: () => void): () => void {
  listeners.add(listener);
  return () => void listeners.delete(listener);
}

/** The current language; re-renders the component when it changes. */
export const useLang = (): Lang => useSyncExternalStore(subscribeLang, getLang, getLang);

export type Params = Record<string, string | number>;

/**
 * Plural marks: each "(s)" or "(es)" follows the number written before it, French style (0 and 1 singular) or English
 * style (1 singular): "1 page(s)" -> "1 page", "2 page(s)" -> "2 pages".
 */
function plurals(text: string, in_: Lang): string {
  let n: number | null = null;
  return text.replace(/(\d+(?:[.,]\d+)?)|\((s|es)\)/g, (m, num: string | undefined, suffix: string | undefined) => {
    if (num !== undefined) {
      n = Number(num.replace(',', '.'));
      return m;
    }
    const singular = n !== null && (in_ === 'fr' ? n < 2 : n === 1);
    return singular ? '' : suffix!;
  });
}

/** The text of `key` in the current language, `{name}` placeholders filled from `params`. */
export function t(key: Key, params: Params = {}, in_: Lang = lang): string {
  return plurals(TABLES[in_][key].replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m)), in_);
}

/** True when `key` is a known key (server codes are checked before being looked up). */
export const hasKey = (key: string): key is Key => key in fr;

/** Error text of a server or device code, a generic one for an unknown code. */
export const errorText = (code: string) => (hasKey(`error.${code}`) ? t(`error.${code}` as Key) : t('error.unknown'));

/** A photo-quality message in the current language. */
export const qualityText = (fr_: string) => (lang === 'en' ? (QUALITY_EN[fr_] ?? fr_) : fr_);

/** dd/mm/yyyy in French, dd/mm/yyyy too in English (the register's own format), from an ISO date. */
export const fmtDate = (iso: string) => new Date(iso).toLocaleDateString(lang === 'fr' ? 'fr-FR' : 'en-GB');
/** Short time of day, or the date when it is not today. */
export function fmtWhen(iso: string, now = new Date()): string {
  const d = new Date(iso);
  const sameDay = d.toDateString() === now.toDateString();
  return sameDay ? d.toLocaleTimeString(lang === 'fr' ? 'fr-FR' : 'en-GB', { hour: '2-digit', minute: '2-digit' }) : fmtDate(iso);
}

